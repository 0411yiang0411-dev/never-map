CREATE TABLE IF NOT EXISTS quota (
 id INTEGER PRIMARY KEY CHECK(id=1), month TEXT NOT NULL,
 class_a INTEGER NOT NULL DEFAULT 0, class_b INTEGER NOT NULL DEFAULT 0,
 bytes INTEGER NOT NULL DEFAULT 0, verified INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS scene (
 id INTEGER PRIMARY KEY CHECK(id=1), revision INTEGER NOT NULL DEFAULT 0,
 body TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS assets (
 id TEXT PRIMARY KEY, bytes INTEGER NOT NULL, content_type TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'reserved'
);
